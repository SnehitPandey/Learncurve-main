const formatDate = (date) => {
    // Use UTC to avoid timezone issues
    const year = date.getFullYear();
    const month = String(date.getMonth() + 1).padStart(2, '0');
    const day = String(date.getDate()).padStart(2, '0');
    return `${year}-${month}-${day}`;
};

const parseDate = (dateStr) => {
    // Parse as local date to avoid timezone shifts
    const [year, month, day] = String(dateStr).split('-').map(Number);
    return new Date(year, month - 1, day);
};

const addDays = (dateStr, days) => {
    const date = parseDate(dateStr);
    date.setDate(date.getDate() + days);
    return formatDate(date);
};

// Format date for display (7 Aug)
const formatDisplayDate = (dateStr) => {
    if (!dateStr) return "";
    const date = parseDate(dateStr);
    if (Number.isNaN(date.getTime())) return String(dateStr);
    const day = date.getDate();
    const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 
                   'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
    const month = months[date.getMonth()];
    return `${day} ${month}`;
};

const parseDailyMinutes = (val) => {
    if (!val) return 30;
    const s = String(val).toLowerCase();
    if (s.includes("15")) return 15;
    if (s.includes("30")) return 30;
    if (s.includes("45")) return 45;
    if (s.includes("1h") || s.includes("1 hr") || s.includes("60")) return 60;
    if (s.includes("1.5") || s.includes("90")) return 90;
    if (s.includes("2h") || s.includes("2 hr") || s.includes("120")) return 120;
    const match = s.match(/(\d+)/);
    return match ? Number(match[1]) : 30;
};

const PLACEHOLDER_TASKS = 5;

const TIMEFRAME_DAYS = {
    "1day": 1, "3days": 3, "1week": 7, "2weeks": 14, "3weeks": 21, "6weeks": 42,
    "1month": 30, "2months": 60, "3months": 90, "4months": 120,
    "5months": 150, "6months": 180, "1year": 365
};

/** "3months" / "custom-45" -> days, or null when it cannot be parsed. */
const timeframeToDays = (timeframe) => {
    if (!timeframe) return null;
    const key = String(timeframe).trim().toLowerCase().replace(/[\s_-]+/g, "");
    if (TIMEFRAME_DAYS[key]) return TIMEFRAME_DAYS[key];
    const custom = /^custom(\d+)$/.exec(key);
    if (custom) {
        const total = Number(custom[1]);
        return Number.isFinite(total) && total > 0 ? total : null;
    }
    const numeric = /^(\d+)(day|week|month|year)s?$/.exec(key);
    if (!numeric) return null;
    const unitDays = { day: 1, week: 7, month: 30, year: 365 };
    const total = Number(numeric[1]) * unitDays[numeric[2]];
    return Number.isFinite(total) && total > 0 ? total : null;
};

// Generate comprehensive roadmap with single dates
const generateRoadmapWithDates = (aiSummary, timeframe) => {
    // If structured modules were generated by AI, use them directly
    if (Array.isArray(aiSummary?.modules) && aiSummary.modules.length > 0) {
        return aiSummary.modules.map((mod, index) => {
            const rawTitle = typeof mod.title === "string" ? mod.title : `Module ${index + 1}`;
            const cleanTitle = rawTitle.replace(/^(Week|Module)\s+\d+(-\d+)?\s*:\s*/i, '').trim();
            const rawSubs = Array.isArray(mod.subtopics) && mod.subtopics.length > 0
                ? mod.subtopics.map(s => String(s).trim()).filter(Boolean)
                : Array.isArray(mod.tasks)
                ? mod.tasks.filter(t => t.kind !== "practice").map(t => String(t.title || "").trim()).filter(Boolean)
                : [];
            const subs = rawSubs.length >= 2 ? rawSubs : [
                `Core fundamentals of ${cleanTitle}`,
                `Hands-on application of ${cleanTitle}`
            ];
            return {
                id: index,
                title: cleanTitle,
                endDate: mod.endDate || formatDate(new Date(Date.now() + (index + 1) * 7 * 86400000)),
                enabled: true,
                description: mod.summary || `Complete ${cleanTitle.toLowerCase()} by this date`,
                subtopics: subs,
                completed: 0,
                total: Math.max(PLACEHOLDER_TASKS, subs.length + 1)
            };
        });
    }

    const baseRoadmap = (Array.isArray(aiSummary?.roadmapPreview) && aiSummary.roadmapPreview.length > 0)
        ? aiSummary.roadmapPreview
        : [
            "Core fundamentals and setup",
            "Practical projects and exercises",
            "Advanced concepts and portfolio",
            "Capstone synthesis and review"
        ];

    // Remove Week and Module prefixes from existing roadmap items
    const cleanRoadmap = (Array.isArray(baseRoadmap) ? baseRoadmap : [])
        .filter(item => typeof item === "string")
        .map(item => item.replace(/^(Week|Module)\s+\d+(-\d+)?\s*:\s*/i, '').trim());

    const today = new Date();
    const rawSubtopics = Array.isArray(aiSummary?.subtopics) ? aiSummary.subtopics : [];

    const totalDays = timeframeToDays(timeframe) || TIMEFRAME_DAYS["1month"];
    const count = Math.max(1, cleanRoadmap.length);
    const step = Math.max(1, Math.round(totalDays / count));

    return cleanRoadmap.map((item, index) => {
        const endDate = new Date(today);
        endDate.setDate(today.getDate() + ((index + 1) * step));

        const weekSubtopics = Array.isArray(rawSubtopics[index])
            ? rawSubtopics[index]
                .map(s => (typeof s === "string" ? s.trim() : String(s?.title || "").trim()))
                .filter(Boolean)
            : [];

        return {
            id: index,
            title: item,
            endDate: formatDate(endDate),
            enabled: true,
            description: `Complete ${item.toLowerCase()} by this date`,
            subtopics: weekSubtopics.length >= 2 ? weekSubtopics : [
                `Core fundamentals of ${item}`,
                `Hands-on application of ${item}`
            ],
            completed: 0,
            total: Math.max(PLACEHOLDER_TASKS, weekSubtopics.length + 1)
        };
    });
};

const roadmapWeekCount = (timeframe) => {
    const days = timeframeToDays(timeframe) || TIMEFRAME_DAYS["1month"];
    return Math.max(1, Math.min(24, Math.ceil(days / 7)));
};

export const spreadMilestoneDates = (startDateStr, totalDays, count) => {
    if (count <= 0) return [];
    const baseDate = parseDate(startDateStr);
    const out = [];
    for (let i = 0; i < count; i++) {
        const offsetDays = Math.round((totalDays * (i + 1)) / count);
        const dt = new Date(baseDate);
        dt.setDate(baseDate.getDate() + offsetDays);
        out.push(formatDate(dt));
    }
    return out;
};

const withEvenlySpreadDates = (milestones, timeframe, startDateStr) => {
    const start = startDateStr || formatDate(new Date());
    const totalDays = timeframeToDays(timeframe) || TIMEFRAME_DAYS["1month"];
    const count = Math.max(1, milestones.length);
    const dates = spreadMilestoneDates(start, totalDays, count);

    return milestones.map((m, index) => {
        return { ...m, endDate: dates[index] };
    });
};

